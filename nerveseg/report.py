"""Render results/metrics.json (two-site model, version 3) into docs/MODEL_CARD.md and figures."""
import json
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from sklearn.metrics import roc_curve

from nerveseg.sites import load_all

FIG = 'docs/figures'
ROWS = [('Sensitivity', 'sensitivity'), ('Specificity', 'specificity'), ('PPV', 'ppv'), ('NPV', 'npv'),
        ('AUROC (presence)', 'auroc_presence'), ('Dice, labelled positives', 'dice_labelled_positives'),
        ('Dice, correct detections', 'dice_true_detections'), ('Kaggle mean Dice', 'kaggle_mean_dice'),
        ('Centroid error, px (median)', 'centroid_error_px_median'), ('Brier score (presence)', 'brier_presence')]


def cell(m):
    return f"{m['estimate']:.3f} ({m['ci95'][0]:.3f}–{m['ci95'][1]:.3f})" if m else '–'


def main():
    r = json.load(open('results/metrics.json'))
    v2 = json.load(open('results/v2_metrics.json'))
    ext = json.load(open('results/external_metrics.json'))
    os.makedirs(FIG, exist_ok=True)
    d = load_all('AB')
    p = np.load('results/test_pred_ensemble.npz')
    y = d['area'][p['idx']] > 0
    fig, ax = plt.subplots(1, 2, figsize=(10, 4))
    for s, name, c in ((0, 'Site A (Kaggle)', '#c97a0f'), (1, 'Site B (second hospital)', '#1f8aa3')):
        k = p['site'] == s
        fpr, tpr, _ = roc_curve(y[k], p['cls'][k])
        ax[0].plot(fpr, tpr, color=c, label=name)
        bins = np.linspace(0, 1, 11); b = np.digitize(p['cls'][k], bins[1:-1])
        ax[1].plot([p['cls'][k][b == i].mean() for i in range(10) if (b == i).sum() > 4],
                   [y[k][b == i].mean() for i in range(10) if (b == i).sum() > 4], 'o-', color=c, label=name)
    for a in ax: a.plot([0, 1], [0, 1], ':', color='grey'); a.legend(fontsize=8)
    ax[0].set(xlabel='1 − specificity', ylabel='Sensitivity', title='Presence ROC, locked test (ensemble)')
    ax[1].set(xlabel='Predicted probability', ylabel='Observed rate', title='Calibration, locked test (ensemble)')
    plt.tight_layout(); plt.savefig(f'{FIG}/test_performance.png', dpi=110)

    rule = r['decision_rule']
    A, B = 'test_single_fold0_siteA', 'test_single_fold0_siteB'
    L = ['# Model card: Plexus Finder (version 3, two sites)', '',
         'Generated by `nerveseg/report.py` from `results/`. Do not edit numbers by hand.', '',
         '## Intended use', '',
         'Research and teaching only. Outlines the brachial plexus on a single interscalene ultrasound frame.',
         'Not a medical device. Must not guide a needle or any clinical decision.', '',
         '## Data', '',
         '- Site A: Kaggle Ultrasound Nerve Segmentation training set, 5,635 frames, 47 patients, one plexus outline per frame.',
         '- Site B: `alexcolmenero/ultrasonic-brachial-plexus`, 955 frames, 88 patients, a different hospital and scanner. '
         'Nerve roots are outlined separately; the reference is their convex hull. Licence listed as unknown.',
         f"- Locked test sets, fixed before training: site A {len(r['test_siteA_patients'])} patients "
         f"({r['test_siteA_n_images']} frames, {r['test_siteA_positive_rate']:.0%} with nerve); site B "
         f"{len(r['test_siteB_patients'])} patients ({r['test_siteB_n_images']} frames, {r['test_siteB_positive_rate']:.0%} with nerve).",
         '- Everything else is split by patient into 5 folds for training and tuning.',
         f"- Label noise at site A: {r['n_siteA_test_images_in_contradictory_pairs']} test frames sit in a near-identical pair "
         'with the opposite label. About a quarter of near-duplicate pairs in the full set disagree.', '',
         '## Method', '',
         '- U-Net with an ImageNet-pretrained MobileNetV2 encoder, 4.1M parameters, plus a nerve-present head.',
         '- Input 224×288 greyscale from an area-average resize, identical in training, evaluation and the browser app.',
         '- Loss: pixel BCE + Dice on labelled-positive frames + 0.5 × presence BCE. AdamW, one-cycle, 15 epochs, '
         'best checkpoint by validation loss.',
         '- Augmentation: horizontal flip, ±10° rotation, ±10% scale, ±8% shift, gamma and gain.',
         '- Training drops site-A unlabelled frames that are near-duplicates of a labelled frame from the same patient.',
         f"- Decision rule tuned on pooled out-of-fold predictions: present if probability ≥ {rule['t_cls']} and the largest "
         f"region ≥ {rule['min_area_px_full_res']} px at 420×580, scaled by image area.",
         '- The app ships the fold-0 model, so the "shipped" columns are exactly what the app runs.', '',
         '## Results', '',
         'Point estimate with 95% CI from 2,000 bootstrap resamples of patients, at each frame\'s native resolution.', '',
         '| Measure | Dev OOF, site A | Dev OOF, site B | Test, site A, shipped | Test, site B, shipped | Test, site A, consistent labels |',
         '|---|---|---|---|---|---|']
    for name, k in ROWS:
        L.append(f"| {name} | {cell(r['development_oof_siteA'].get(k))} | {cell(r['development_oof_siteB'].get(k))} | "
                 f"{cell(r[A].get(k))} | {cell(r[B].get(k))} | {cell(r['test_single_fold0_siteA_consistent_labels_only'].get(k))} |")
    L += ['', f"Always answering \"no nerve\" scores a Kaggle mean Dice of {r['test_siteA_baseline_always_empty']:.3f} at site A "
          f"and {r['test_siteB_baseline_always_empty']:.3f} at site B.", '',
          '5-fold ensemble, for reference: site A sensitivity ' + cell(r['test_ensemble5_siteA']['sensitivity']) +
          ', specificity ' + cell(r['test_ensemble5_siteA']['specificity']) + '; site B sensitivity ' +
          cell(r['test_ensemble5_siteB']['sensitivity']) + '.', '',
          '![Test performance](figures/test_performance.png)', '',
          '## Version history and test-set use', '',
          'Every look at a locked test set is listed here, so readers can judge how clean each estimate is.', '',
          '| Version | Trained on | Site A test (9 pts) | Site B (88 pts, then 18 test pts) |', '|---|---|---|---|',
          '| 1 | Site A, scikit-image resize | sens 0.62, spec 0.80 | not run |',
          f"| 2 | Site A, browser resize | sens {v2['test_single_fold0']['sensitivity']['estimate']:.2f}, spec "
          f"{v2['test_single_fold0']['specificity']['estimate']:.2f} | external validation, all 88 patients: sens "
          f"{ext['sensitivity']['estimate']:.2f}. **Failed.** |",
          f"| 3 | Sites A and B | sens {r[A]['sensitivity']['estimate']:.2f}, spec {r[A]['specificity']['estimate']:.2f} | "
          f"18 held-out patients: sens {r[B]['sensitivity']['estimate']:.2f}, spec {r[B]['specificity']['estimate']:.2f} |", '',
          'Protocols were committed before each run: `docs/EXTERNAL_VALIDATION_PROTOCOL.md`, `docs/TWO_SITE_PROTOCOL.md`.', '',
          '## Limitations', '',
          '- No untouched external site remains. Version 3 makes no claim about a third scanner.',
          '- Site A\'s test patients have now been scored three times, which makes that estimate less clean.',
          '- Site B has only 3 to 6% nerve-free frames, so its specificity is imprecise.',
          '- The two sites label differently: one plexus outline against separate roots. The hull reference is an approximation.',
          '- One annotator per site, no inter-rater agreement. Pixel spacing unknown, so errors are in pixels.',
          '- Single frames. No temporal smoothing or live video.', '']
    open('docs/MODEL_CARD.md', 'w').write('\n'.join(L))
    print('wrote docs/MODEL_CARD.md')


if __name__ == '__main__':
    main()
