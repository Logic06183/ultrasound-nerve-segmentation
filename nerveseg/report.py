"""Render results/metrics.json into docs/MODEL_CARD.md plus figures in docs/figures/."""
import json
import os

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from sklearn.metrics import roc_curve

from nerveseg.data import load_cache

FIG = 'docs/figures'
ROWS = [('Sensitivity', 'sensitivity'), ('Specificity', 'specificity'), ('PPV', 'ppv'), ('NPV', 'npv'),
        ('AUROC (presence)', 'auroc_presence'), ('Dice, labelled positives', 'dice_labelled_positives'),
        ('Dice, correct detections', 'dice_true_detections'), ('Kaggle mean Dice', 'kaggle_mean_dice'),
        ('Centroid error, px (median)', 'centroid_error_px_median'), ('Brier score (presence)', 'brier_presence')]


def cell(m):
    return f"{m['estimate']:.3f} ({m['ci95'][0]:.3f}–{m['ci95'][1]:.3f})" if m else '–'


def main():
    r = json.load(open('results/metrics.json'))
    os.makedirs(FIG, exist_ok=True)
    _, _, meta, area = load_cache()
    p = np.load('results/test_pred_ensemble.npz')
    y = area[p['idx']] > 0
    fig, ax = plt.subplots(1, 3, figsize=(13, 4))
    fpr, tpr, _ = roc_curve(y, p['cls'])
    ax[0].plot(fpr, tpr, color='#c97a0f'); ax[0].plot([0, 1], [0, 1], ':', color='grey')
    ax[0].set(xlabel='1 − specificity', ylabel='Sensitivity', title='Presence ROC, test patients (ensemble)')
    bins = np.linspace(0, 1, 11); k = np.digitize(p['cls'], bins[1:-1])
    ax[1].plot([0, 1], [0, 1], ':', color='grey')
    ax[1].plot([p['cls'][k == b].mean() for b in range(10) if (k == b).any()],
               [y[k == b].mean() for b in range(10) if (k == b).any()], 'o-', color='#c97a0f')
    ax[1].set(xlabel='Predicted probability', ylabel='Observed rate', title='Calibration, test patients (ensemble)')
    pp = r['test_single_fold0_per_patient']
    ids = sorted(pp, key=lambda s: pp[s]['kaggle_mean_dice'])
    ax[2].barh([f'pt {s}' for s in ids], [pp[s]['kaggle_mean_dice'] for s in ids], color='#1f8aa3')
    ax[2].set(xlabel='Kaggle mean Dice', title='Per test patient (shipped model)', xlim=(0, 1))
    plt.tight_layout(); plt.savefig(f'{FIG}/test_performance.png', dpi=110)

    rule = r['decision_rule']
    lines = [
        '# Model card: Plexus Finder', '',
        'Generated by `nerveseg/report.py` from `results/metrics.json`. Do not edit numbers by hand.', '',
        '## Intended use', '',
        'Research and teaching only. Highlights the brachial plexus on a single interscalene ultrasound frame.',
        'Not a medical device. Must not guide a needle or any clinical decision.', '',
        '## Data', '',
        '- Source: Kaggle Ultrasound Nerve Segmentation (2016) training set, 5,635 frames from 47 patients, one annotator per frame.',
        f"- Locked test set: {len(r['test_patients'])} patients ({r['n_test_images']} frames), chosen at random with a fixed seed before any training. "
        f"Positive rate {r['test_positive_rate']:.1%}.",
        '- Development set: the other 38 patients, in 5 patient-grouped folds.',
        f"- Label noise: {r['n_test_images_in_contradictory_pairs']} test frames sit in a near-identical pair with the opposite label. "
        'Across the full dataset about a quarter of near-duplicate pairs disagree (`analysis/data_profile.json`).', '',
        '## Method', '',
        '- U-Net, MobileNetV2 encoder pretrained on ImageNet, 4.1M parameters, plus a nerve-present classification head.',
        '- Input 224×288 greyscale. Loss: pixel BCE + Dice on labelled-positive frames + 0.5 × presence BCE.',
        '- Augmentation: horizontal flip, ±10° rotation, ±10% scale, ±8% shift, gamma and gain.',
        '- Training drops unlabelled frames that are near-duplicates of a labelled frame from the same patient.',
        '- AdamW with a one-cycle schedule, 15 epochs, best checkpoint by validation loss. A first 40-epoch run on fold 0 '
        'overfitted after epoch 12 (validation loss 0.60 rising to 1.29), so all folds were retrained at 15 epochs. '
        'That choice used fold-0 validation patients only, never the test patients.',
        f"- Decision rule tuned on out-of-fold predictions only: present if probability ≥ {rule['t_cls']} and the largest "
        f"region ≥ {rule['min_area_px_full_res']} px at 420×580.", '',
        '## Results', '',
        'Point estimate with 95% CI from 2,000 bootstrap resamples of patients. All metrics at 420×580 against the original masks.', '',
        '| Measure | Development (out-of-fold, 38 pts) | Test: shipped single model | Test: 5-fold ensemble | Test: shipped, consistent labels only |',
        '|---|---|---|---|---|',
    ]
    for name, k in ROWS:
        lines.append(f"| {name} | {cell(r['development_oof'].get(k))} | {cell(r['test_single_fold0'].get(k))} | "
                     f"{cell(r['test_ensemble5'].get(k))} | {cell(r['test_single_fold0_consistent_labels_only'].get(k))} |")
    lines += ['', f"Baseline: always answering \"no nerve\" scores a Kaggle mean Dice of {r['test_baseline_always_empty_kaggle_mean_dice']:.3f} on the test set.",
              '', '![Test performance](figures/test_performance.png)', '',
              '## Limitations', '',
              '- One public dataset, one scanner family, one annotator, no inter-rater agreement.',
              '- Test patients come from the same collection as training patients, so this is internal validation only.',
              '- Pixel spacing is unknown, so localisation errors are in pixels, not millimetres.',
              '- Single frames. No temporal smoothing or live video.',
              '- Kaggle leaderboard scores used a different, hidden test set and are not comparable.',
              '- The test set was scored twice. Version 1 used scikit-image resizing for training and scored sensitivity 0.62, '
              'specificity 0.80 and Kaggle score 0.70 on test. Version 2, reported above, switched training to the browser\'s '
              'area-average resize so the shipped app matches validation exactly. That switch was decided before version 2 '
              'was scored, for parity reasons, not because of its test results.', '']
    if os.path.exists('results/external_metrics.json'):
        e = json.load(open('results/external_metrics.json'))
        x = json.load(open('results/external_exploratory_intensity.json'))
        lines += ['## External validation: failed', '',
                  f"Pre-registered in `docs/EXTERNAL_VALIDATION_PROTOCOL.md` and run once with the frozen shipped model on "
                  f"{e['n_frames']} frames from {e['n_patients']} patients scanned elsewhere on a different machine.", '',
                  '| Measure | Estimate (95% CI) |', '|---|---|',
                  f"| Sensitivity, {e['n_nerve_frames']} nerve frames | {cell(e['sensitivity'])} |",
                  f"| Specificity, {e['n_frames'] - e['n_nerve_frames']} nerve-free frames | {cell(e['specificity'])} |",
                  f"| Predicted region touches a nerve | {cell(e['hit_rate_nerve_frames'])} |", '',
                  f"The model found no nerve in any external frame. Median presence probability was "
                  f"{e['presence_prob_median_nerve_frames']:.3f} on nerve frames. The external images are much darker "
                  f"(mean grey 45 against 98) and come from a different scanner.", '',
                  f"Exploratory only, because it uses the external images themselves: matching each image's brightness "
                  f"and contrast to the training data does not fix it (presence AUROC {x['auroc_presence']:.2f}). "
                  f"The shift is deeper than brightness. **This model works only on images like its training site's.** "
                  f"Multi-site training data is the first requirement for any further claim.", '']
    open('docs/MODEL_CARD.md', 'w').write('\n'.join(lines))
    print('wrote docs/MODEL_CARD.md')


if __name__ == '__main__':
    main()
